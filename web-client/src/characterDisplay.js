export const characters = Object.fromEntries(Object.keys(characterNames).map((key, index) => [key, {
  number: index + 1, title: titles[index][0], shortName: titles[index][1], kana: characterNames[key],
}]))

export function characterDisplayName(key) {
  const entry = typeof key === 'string' && Object.hasOwn(characters, key) ? characters[key] : null
  return entry ? entry.title + ' ' + entry.kana : '人物不明（表示診断）'
}
export function characterKana(key) {
  return typeof key === 'string' && Object.hasOwn(characterNames, key) ? characterNames[key] : '人物不明'
}
